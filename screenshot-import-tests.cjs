'use strict'
const fs=require('node:fs')
const assert=require('node:assert/strict')
const api=require('./api/screenshot-transaction.js')

const client=fs.readFileSync('screenshot-import-v44.js','utf8')
const css=fs.readFileSync('screenshot-import-v44.css','utf8')
const index=fs.readFileSync('index.html','utf8')
const sw=fs.readFileSync('sw.js','utf8')
const server=fs.readFileSync('local-server.mjs','utf8')
const build=fs.readFileSync('build.mjs','utf8')
const workflow=fs.readFileSync('.github/workflows/ios-sideload.yml','utf8')
const endpoint=fs.readFileSync('api/screenshot-transaction.js','utf8')

assert.equal(api._test.validDate('2026-08-13'),'2026-08-13')
assert.equal(api._test.validDate('13.08.2026'),'')
assert.equal(api._test.validImage('data:image/png;base64,aGVsbG8='),true)
assert.equal(api._test.validImage('data:text/plain;base64,aGVsbG8='),false)
assert.deepEqual(api._test.normalize({recognized:true,title:'  BILLA   Graz ',amount:'12.349',type:'expense',date:'2026-08-13',category:'Lebensmittel',currency:'eur',confidence:1.2,note:' Karte '}),{recognized:true,title:'BILLA Graz',amount:12.35,type:'expense',date:'2026-08-13',category:'Lebensmittel',currency:'EUR',confidence:1,note:'Karte'})
assert.equal(api._test.normalize({recognized:true,title:'X',amount:0,type:'expense',date:'',category:'x'}).recognized,false)
assert.equal(api._test.outputText({output:[{content:[{type:'output_text',text:'{"ok":true}'}]}]}),'{"ok":true}')

assert.ok(endpoint.includes("process.env.OPENAI_API_KEY"),'OpenAI-Key darf nicht im Client liegen')
assert.ok(endpoint.includes("process.env.OPENAI_SCREENSHOT_MODEL||'gpt-5-mini'"),'Screenshot-Modell fehlt')
assert.ok(endpoint.includes("store:false"),'Responses dürfen für Screenshot-Import nicht gespeichert werden')
assert.ok(endpoint.includes("type:'input_image'"),'Bild-Input fehlt')
assert.ok(endpoint.includes("detail:'high'"),'Screenshot wird nicht hochauflösend analysiert')
assert.ok(endpoint.includes("type:'json_schema'"),'Strukturierte Extraktion fehlt')
assert.ok(endpoint.includes("req.method!=='POST'"),'Screenshot-API akzeptiert falsche Methoden')
assert.ok(endpoint.includes("Access-Control-Allow-Origin','*'"),'Native iOS CORS fehlt')

assert.ok(client.includes("[data-v3=\"plus\"]"),'Plus-Menü wird nicht erweitert')
assert.ok(client.includes('Screenshot importieren'),'Screenshot-Option fehlt')
assert.ok(client.includes("fetch('/api/screenshot-transaction'"),'Screenshot-API wird nicht aufgerufen')
assert.ok(client.includes('Buchung prüfen'),'Kontrollschritt vor Speichern fehlt')
assert.ok(client.includes('Core.saveState(state,{method:\'manual\'})'),'Erkannte Buchung wird nicht lokal gespeichert')
assert.ok(client.includes('findDuplicate(tx)'),'Duplikatschutz fehlt')
assert.ok(client.includes('kommt erst mit deinem manuellen Sync in die Datenbank'),'Local-First-Hinweis fehlt')
assert.ok(!client.includes('OPENAI_API_KEY'),'API-Schlüssel darf nie im Browsercode stehen')
assert.ok(css.includes('.v44-shot-review')&&css.includes('.v44-shot-spinner'),'Screenshot-UI Styling fehlt')

assert.ok(index.includes('/screenshot-import-v44.css?v=4.4.0-r22'),'Screenshot-CSS wird nicht geladen')
assert.ok(index.includes('/screenshot-import-v44.js?v=4.4.0-r22'),'Screenshot-JS wird nicht geladen')
assert.ok(index.indexOf('/screenshot-import-v44.js')<index.indexOf('/app-v3.js'),'Screenshot-Plus-Interceptor muss vor app-v3 laden')
assert.ok(sw.includes('/screenshot-import-v44.js?v=4.4.0-r22')&&sw.includes('/screenshot-import-v44.css?v=4.4.0-r22'),'Screenshot-Assets fehlen im PWA-Cache')
assert.ok(server.includes("url.pathname==='/api/screenshot-transaction'"),'Lokaler Screenshot-Endpunkt fehlt')
assert.ok(build.includes("'screenshot-import-v44.js'")&&build.includes("'api/screenshot-transaction.js'"),'Screenshot-Import fehlt im Build')
assert.ok(workflow.includes("'screenshot-import-v44.js'")||workflow.includes("- 'screenshot-import-v44.js'"),'iOS-Build reagiert nicht auf Screenshot-Modul')

console.log('NEST V4.4.0 screenshot-to-booking, review, local-first and AI extraction regression tests passed')
