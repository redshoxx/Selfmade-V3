const fs=require('node:fs')
function read(f){return fs.readFileSync(f,'utf8')}
function ok(cond,msg){if(!cond)throw new Error(msg)}
const nav=read('v322-nav.js'),index=read('index.html'),sw=read('sw.js'),build=read('build.mjs'),pkg=JSON.parse(read('package.json'))
ok(pkg.version==='4.0.0','package version ist nicht 4.0.0')
ok(nav.includes("RELEASE='4.0.0'"),'V4 release fehlt im Navigationsmodul')
ok(nav.includes("data-route','overview"),'Übersicht-Button oben fehlt')
ok(nav.includes("oldHome.remove()"),'Übersicht wird nicht aus Bottom-Bar entfernt')
ok(nav.includes('v322-top-actions'),'Top-Actions fehlen')
ok(nav.includes('grid-template-columns:repeat(5'),'5er Bottom-Navigation fehlt')
ok(nav.includes('/v4-lidl.js?v=4.0.0-r14')&&nav.includes('/v4-lidl.css?v=4.0.0-r14'),'V4 Lidl Fallback-Loader fehlt')
ok(index.includes('/v322-nav.js?v=4.0.0-r14'),'V4 Navigation wird nicht direkt geladen')
ok(index.includes('/v4-lidl.js?v=4.0.0-r14')&&index.includes('/v4-lidl.css?v=4.0.0-r14'),'V4 Lidl Assets werden nicht direkt geladen')
ok(index.indexOf('/v322-nav.js')>index.indexOf('/v32-bookings.js'),'Navigation muss nach Buchungsmodul geladen werden')
ok(sw.includes('/v322-nav.js?v=4.0.0-r14'),'V4 Navigation fehlt im Service Worker')
ok(sw.includes('/v4-lidl.js?v=4.0.0-r14')&&sw.includes('/v4-lidl.css?v=4.0.0-r14'),'V4 Lidl Assets fehlen im Service Worker')
ok(build.includes("'v322-nav.js'")&&build.includes("'v4-lidl.js'"),'Navigation/V4 fehlen im Build')
console.log('NEST V4 navigation and loader tests passed')
